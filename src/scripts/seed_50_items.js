async function seed() {
  console.log(`Starting to seed ${itemsToSeed.length} additional items into Supabase...`);

  const payload = JSON.stringify(itemsToSeed);
  const options = {
    hostname: 'pjyyjzghatmgvyufcbln.supabase.co',
    path: '/rest/v1/items',
    method: 'POST',
    headers: {
      'apikey': SERVICE_KEY,
      'Authorization': `Bearer ${SERVICE_KEY}`,
      'Content-Type': 'application/json',
      'Prefer': 'return=representation',
      'Content-Length': Buffer.byteLength(payload),
    },
  };

  const req = https.request(options, (res) => {
    let data = '';
    res.on('data', chunk => data += chunk);
    res.on('end', () => {
      if (res.statusCode >= 200 && res.statusCode < 300) {
        const inserted = JSON.parse(data);
        console.log(`SUCCESS! Inserted ${inserted.length} items. Status: ${res.statusCode}`);
      } else {
        console.error(`FAILED with status ${res.statusCode}:`, data);
      }
    });
  });

  req.on('error', (e) => {
    console.error('Request error:', e);
  });

  req.write(payload);
  req.end();
}

